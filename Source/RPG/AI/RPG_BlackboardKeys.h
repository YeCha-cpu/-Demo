#pragma once

#include "CoreMinimal.h"

/**
 * 黑板键名的集中定义。
 *
 * ══════════════════════════════════════════════════════════════════════
 * 【为什么需要这个文件】
 * ══════════════════════════════════════════════════════════════════════
 * 黑板读写全靠 FName，而 **FName 拼错编译期不报错**：
 *
 *     Blackboard->GetValueAsObject(FName("TargetActro"));   // 少了个 e
 *
 * 这行代码会安安静静地返回 nullptr —— 表现出来就像"AI 没发现玩家"，
 * 你会去查感知配置、查碰撞通道、查阵营设置，就是想不到是键名拼错了。
 *
 * 和 GameplayTag 用 C++ 声明（而不是纯 ini）是同一个理由：
 * 把它变成真正的 C++ 变量，拼错就编译不过。
 *
 * ══════════════════════════════════════════════════════════════════════
 * 【和编辑器的一致性】
 * ══════════════════════════════════════════════════════════════════════
 * 在 `BB_RPG_Enemy` 黑板资产里建键时，名字必须和这里**逐字一致**（区分大小写）。
 * 类型也必须对得上 —— 键存在但类型不对时，SetValueAsXxx 会静默失败。
 *
 * 键名和类型的对照表见 Docs/PHASE5_AI_SETUP.md。
 */
namespace RPGBlackboardKeys
{
	// ══════════════════════════════════════════════════════════════════
	//  自身
	// ══════════════════════════════════════════════════════════════════

	// SelfActor 用引擎自带的 FBlackboard::KeySelf，
	// 不在这里重复定义 —— 引擎在建黑板资产时会自动加上这个键。
	// 需要时 #include "BehaviorTree/Blackboard/BlackboardKey.h" 后用 FBlackboard::KeySelf。

	// ══════════════════════════════════════════════════════════════════
	//  目标相关（由 AIController 的感知回调写）
	// ══════════════════════════════════════════════════════════════════

	/** Object —— 当前锁定的目标（玩家）。为空表示不在战斗 */
	extern const FName TargetActor;

	/**
	 * Vector —— 目标最后一次被看到的位置。
	 *
	 * 和 TargetActor 分开是有意的：视野丢失后 TargetActor 会被清掉，
	 * 但这个位置**要保留** —— AI 应该去"最后看到你的地方"找一圈，
	 * 而不是立刻遗忘跑回去巡逻。这是"有脑子"和"很傻"的分界线。
	 */
	extern const FName LastKnownLocation;

	/** Bool —— 目标此刻是否在感知范围内（和 TargetActor 的区别：这个是即时的） */
	extern const FName bTargetVisible;

	// ══════════════════════════════════════════════════════════════════
	//  巡逻相关
	// ══════════════════════════════════════════════════════════════════

	/** Vector —— 出生点。脱战后回到这里 */
	extern const FName HomeLocation;

	/** Vector —— 当前要去的巡逻点 */
	extern const FName PatrolLocation;

	/** Int —— 巡逻点索引。存在黑板上而不是 AI 成员里，是为了能在编辑器里实时看到 */
	extern const FName PatrolIndex;

	// ══════════════════════════════════════════════════════════════════
	//  战斗参数
	// ══════════════════════════════════════════════════════════════════

	/**
	 * Float —— 攻击距离（厘米）。
	 *
	 * 从敌人的配置读出来放黑板，而不是让装饰器去 Cast 敌人 ——
	 * 这样行为树节点不需要知道它服务的具体是哪个角色类。
	 */
	extern const FName AttackRange;

	/** Bool —— 是否处于战斗状态。根选择器用它决定走战斗分支还是巡逻分支 */
	extern const FName bInCombat;
}
